"""KeyUp Dispatch Console provisioning.

A dispatch console is a PC running the KeyUp fork of DVMProject's dvmconsole. It joins the FNE as a
peer, over a WireGuard tunnel to central, and transmits as one subscriber radio ID. Central builds
everything the console needs from the database:

* ``codeplug.yml``  -- the FNE connection (peer ID, password, radio ID) and one channel per talkgroup
                       the console's radio ID may use (same permission rules as a radio);
* ``alias.yml``     -- radio ID -> alias for every subscriber, so the console shows names;
* a WireGuard config for the WireGuard for Windows app (split tunnel: only the FNE goes through it).

The console fetches the codeplug again on start and from File > Sync with KeyUp, so talkgroup and
alias changes made in the web UI reach it without copying files.
"""
from __future__ import annotations

import hashlib
import re

from .dvm import DvmPlan, _scalar, console_password, to_yaml

CHANNELS_PER_ZONE = 24
MAX_CHANNEL_NAME = 21   # dvmconsole truncates longer names, which can make two channels collide
MAX_SYSTEM_NAME = 10
SYSTEM_NAME = "KeyUp"
ZONE_COLORS = ["#2E7D32", "#1565C0", "#6A1B9A", "#EF6C00", "#00838F", "#AD1457"]


def _clean(s: str) -> str:
    return re.sub(r"[\r\n\t]", " ", str(s)).strip()


def channel_mode(tg: dict) -> str:
    """dvmconsole speaks P25, DMR and NXDN; KeyUp talkgroups carry their network mode in bridge_mode."""
    return "dmr" if tg.get("bridge_mode") == "DMR" else "p25"


def build_codeplug(plan: DvmPlan, con: dict) -> dict:
    """Return {"codeplug": yaml, "alias": yaml, "version": hash, "talkgroups": [ids]} for one console."""
    tgs = plan.console_talkgroups(con)
    names: set[str] = set()
    channels = []
    for t in tgs:
        name = _clean(t["name"])[:MAX_CHANNEL_NAME] or f"TG {t['id']}"
        if name in names:
            suffix = f" {t['id']}"
            name = name[:MAX_CHANNEL_NAME - len(suffix)] + suffix
        names.add(name)
        ch = {"name": name, "system": SYSTEM_NAME, "tgid": str(t["id"]), "mode": channel_mode(t)}
        if ch["mode"] == "dmr":
            ch["slot"] = int(t.get("dmr_slot") or 1)
        channels.append(ch)
    zones = []
    for i in range(0, len(channels), CHANNELS_PER_ZONE):
        n = i // CHANNELS_PER_ZONE
        zones.append({"name": "Talkgroups" if len(channels) <= CHANNELS_PER_ZONE else f"Talkgroups {n + 1}",
                      "tabColor": ZONE_COLORS[n % len(ZONE_COLORS)], "channels": channels[i:i + CHANNELS_PER_ZONE]})
    if not zones:
        zones = [{"name": "Talkgroups", "channels": []}]
    pid = con["fne_peer_id"]
    codeplug = {
        "systems": [{
            "name": SYSTEM_NAME[:MAX_SYSTEM_NAME],
            "identity": _clean(con["name"])[:32] or f"CONS{con['id']}",
            "address": plan.fne_host,
            "port": plan.fne_port,
            "peerId": pid,
            "rid": str(con["subscriber_id"]),
            "password": console_password(pid),
            "encrypted": False,
            "aliasPath": "alias.yml",     # the console rewrites this to its own folder
        }],
        "zones": zones,
    }
    cp_yaml = to_yaml(codeplug, f"KeyUp Dispatch Console codeplug for '{_clean(con['name'])}' "
                                f"(peer {pid}, radio {con['subscriber_id']})\n"
                                "Generated by KeyUp -- edit talkgroups and aliases in the KeyUp web UI.")
    # alias.yml is a top-level list of {alias, rid}
    entries = "".join(f"- alias: {_scalar(_clean(s['alias'])[:32] or str(s['id']))}\n  rid: {s['id']}\n"
                      for s in plan.subs if s["enabled"])
    alias_yaml = "# KeyUp generated radio aliases\n" + (entries or "[]\n")
    version = hashlib.sha256((cp_yaml + alias_yaml).encode()).hexdigest()[:16]
    return {"codeplug": cp_yaml, "alias": alias_yaml, "version": version, "talkgroups": [t["id"] for t in tgs]}


def wireguard_conf(private_key: str, cfg: dict, name: str) -> str:
    """WireGuard for Windows tunnel file. Split tunnel: only the KeyUp server's tunnel IP is routed."""
    return (f"# KeyUp Dispatch Console tunnel -- {name}\n"
            "# Import into WireGuard for Windows (Add Tunnel > Import tunnel(s) from file) and activate.\n"
            "[Interface]\n"
            f"PrivateKey = {private_key}\n"
            f"Address = {cfg['address']}\n\n"
            "[Peer]\n"
            f"PublicKey = {cfg['server_public_key']}\n"
            f"Endpoint = {cfg['endpoint']}\n"
            f"AllowedIPs = {cfg['allowed_ips']}\n"
            f"PersistentKeepalive = {cfg['persistent_keepalive']}\n")
